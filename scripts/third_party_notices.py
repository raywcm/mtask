#!/usr/bin/env python3
"""Collect original runtime dependency license texts for supported build targets."""
import argparse
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def expected_files(go):
    modules = {}
    template = '{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}'
    for target in ('linux', 'darwin'):
        env = dict(os.environ, GOOS=target, GOARCH='amd64', CGO_ENABLED='0')
        output = subprocess.check_output([go, 'list', '-deps', '-f', template, './cmd/mtask'], cwd=ROOT, env=env, text=True)
        for row in output.splitlines():
            if not row:
                continue
            name, version, directory = row.split('|')
            if version:
                modules[name] = (version, pathlib.Path(directory))
    files = {}
    rows = []
    for name, (version, directory) in sorted(modules.items()):
        notices = sorted(p for p in directory.iterdir() if p.is_file() and p.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE')))
        if not notices:
            raise SystemExit('No upstream license found for ' + name)
        links = []
        for notice in notices:
            relative = pathlib.Path('licenses') / (name.replace('/', '_') + '@' + version) / notice.name
            files[relative] = notice.read_bytes()
            links.append('[' + notice.name + '](' + relative.as_posix() + ')')
        rows.append('| `' + name + '` | `' + version + '` | ' + ', '.join(links) + ' |')
    intro = '''# Third-party notices

mtask is licensed under the [MIT License](LICENSE). Dependencies retain their
respective licenses and copyright notices. The original upstream texts below
are distributed with the source and binary packages.

Generated by `python3 scripts/third_party_notices.py` from the Linux/macOS
runtime dependency graph of `./cmd/mtask` (CGO disabled). Test and packaging
tools are not linked into mtask. Regenerate after changing Go dependencies;
`--check` verifies that the inventory and copied texts are current.

| Module | Version | Original notices |
| --- | --- | --- |
'''
    files[pathlib.Path('THIRD_PARTY_NOTICES.md')] = (intro + '\n'.join(rows) + '\n').encode()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--go', default=os.environ.get('GO', 'go'))
    args = parser.parse_args()
    files = expected_files(args.go)
    actual = {p.relative_to(ROOT) for p in (ROOT / 'licenses').rglob('*') if p.is_file()}
    stale = actual - files.keys()
    changed = [p for p, content in files.items() if not (ROOT / p).exists() or (ROOT / p).read_bytes() != content]
    if args.check:
        if stale or changed:
            print('Third-party notices need regeneration:', *(str(p) for p in sorted(stale | set(changed))), sep='\n', file=sys.stderr)
            raise SystemExit(1)
    else:
        for p in stale:
            (ROOT / p).unlink()
        for p in changed:
            (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / p).write_bytes(files[p])
    print('PASS original third-party notices: ' + str(len(files) - 1) + ' files')


if __name__ == '__main__':
    main()
